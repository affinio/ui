const dragTrack = async (axis, policy, { boundary = 1, delta = 20, cancel = false } = {}) => {
  await page.getByLabel("Track resize policy").selectOption(policy)
  const sizeLabel = axis === "column" ? "Selected column width" : "Selected row height"
  const totalLabel = axis === "column" ? "Table width" : "Table height"
  const beforeSize = Number(await page.getByLabel(sizeLabel).inputValue())
  const beforeTotal = Number(await page.getByLabel(totalLabel).inputValue())
  const beforeGeometry = await cellGeometry()
  const handle = page.locator(`[data-table-resize="${axis}"][data-table-boundary="${boundary}"]`).first()
  const box = await handle.boundingBox()
  if (!box) throw new Error(`${axis} resize handle missing at boundary ${boundary}`)
  const normal = await handle.evaluate((element, resizeAxis) => {
    const matrix = element.getScreenCTM()
    if (!matrix) throw new Error("resize hit region has no screen matrix")
    const vx = resizeAxis === "column" ? matrix.a : matrix.c
    const vy = resizeAxis === "column" ? matrix.b : matrix.d
    const length = Math.hypot(vx, vy)
    return { x: vx / length, y: vy / length }
  }, axis)
  const point = { x: box.x + box.width / 2, y: box.y + box.height / 2 }
  await page.mouse.move(point.x, point.y)
  await page.mouse.down()
  await page.mouse.move(point.x + normal.x * delta, point.y + normal.y * delta, { steps: 5 })
  await page.waitForTimeout(40)
  const previewGeometry = await cellGeometry()
  if (JSON.stringify(previewGeometry) === JSON.stringify(beforeGeometry)) throw new Error(`${axis} resize preview did not change rendered cell geometry`)
  if (cancel) {
    await page.locator('svg[aria-label="Editable table canvas"]').dispatchEvent("pointercancel", { pointerId: 1 })
    await page.mouse.up()
    await page.waitForTimeout(40)
    if (JSON.stringify(await cellGeometry()) !== JSON.stringify(beforeGeometry)) throw new Error(`${axis} pointer cancellation did not restore original geometry`)
    return
  }
  await page.mouse.up()
  await page.waitForTimeout(40)
  const committedGeometry = await cellGeometry()
  const committedSize = Number(await page.getByLabel(sizeLabel).inputValue())
  const committedTotal = Number(await page.getByLabel(totalLabel).inputValue())
  if (JSON.stringify(previewGeometry) !== JSON.stringify(committedGeometry)) throw new Error(`${axis} rendered preview differs from committed cell geometry`)
  if (Math.abs(committedSize - beforeSize) < 0.01) throw new Error(`${axis} pointer resize did not change the selected track`)
  if (policy === "fixed" && Math.abs(committedTotal - beforeTotal) > 0.01) throw new Error(`fixed ${axis} resize changed the Table total`)
  if (policy === "flexible" && Math.abs(committedTotal - beforeTotal) < 0.01) throw new Error(`flexible ${axis} resize did not change the Table total`)
  await page.getByRole("button", { name: "Undo" }).click()
  if (JSON.stringify(await cellGeometry()) !== JSON.stringify(beforeGeometry)) throw new Error(`${axis} resize undo did not restore original geometry`)
  await page.getByRole("button", { name: "Redo" }).click()
  if (JSON.stringify(await cellGeometry()) !== JSON.stringify(committedGeometry)) throw new Error(`${axis} resize redo did not restore committed geometry`)
}
