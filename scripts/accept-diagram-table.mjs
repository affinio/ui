      await page.mouse.move(first.x + first.width / 2, first.y + first.height / 2)
      await page.mouse.down()
      await page.mouse.move(last.x + last.width / 2, last.y + last.height / 2, { steps: 4 })
      await page.mouse.up()
      if (await grid.locator('[role="gridcell"][aria-selected="true"]').count() < 2) throw new Error("nested transformed range selection failed")
      await page.locator('[data-table-row="1"][data-table-column="1"]').dblclick()
